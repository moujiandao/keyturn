// The single home for snake_case -> camelCase mapping of Zelle tables.

export const mapZelleEvent = (row) => ({
  id: row.id,
  landlordId: row.landlord_id,
  resendEmailId: row.resend_email_id ?? null,
  dedupeKey: row.dedupe_key,
  emailFrom: row.email_from ?? null,
  emailSubject: row.email_subject ?? null,
  receivedAt: row.received_at ?? null,
  rawBody: row.raw_body ?? "",
  rawHeaders: row.raw_headers || {},
  bank: row.bank || "chase",
  direction: row.direction || "unknown",
  payerName: row.payer_name ?? null,
  payerNameNormalized: row.payer_name_normalized ?? null,
  amount: row.amount == null ? null : Number(row.amount),
  sentOn: row.sent_on ?? null,
  memo: row.memo ?? null,
  zelleTxnId: row.zelle_txn_id ?? null,
  parseSource: row.parse_source || "rules",
  parseNotes: row.parse_notes ?? null,
  category: row.category || "rent",
  targetMonth: row.target_month ?? null,
  suggestedTenantIds: Array.isArray(row.suggested_tenant_ids) ? row.suggested_tenant_ids : [],
  suggestedContractId: row.suggested_contract_id ?? null,
  matchReason: row.match_reason ?? null,
  status: row.status || "needs_review",
  postedPaymentIds: Array.isArray(row.posted_payment_ids) ? row.posted_payment_ids : [],
  resolvedAt: row.resolved_at ?? null,
  resolvedBy: row.resolved_by ?? null,
  createdAt: row.created_at ?? null,
  updatedAt: row.updated_at ?? null,
});
